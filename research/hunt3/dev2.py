from base import *
te=pd.read_csv(R+'data/upi-fraud-rings/test.csv'); tr=pd.read_csv(R+'data/upi-fraud-rings/train.csv')
v9=pd.read_csv(R+'submissions/v9_v6_qrrule.csv').rename(columns={'id':'txn_id','label':'v9'}); te=te.merge(v9,on='txn_id')
pd.set_option('display.width',250,'display.max_columns',30,'display.max_rows',300)
te['dn']=te.device_id.str[2:].astype(int); tr['dn']=tr.device_id.str[2:].astype(int)
z=te[te.dn>473631]; print(z.dn.min(), z.dn.max(), z.device_id.nunique())
z['b']=pd.cut(z.dn,np.linspace(473631,z.dn.max()+1,41)).astype(str)
t=z.groupby('b').agg(n=('v9','size'),ndev=('device_id','nunique'),fr=('v9',lambda s:(s!='legit').mean()),ato=('v9',lambda s:(s=='account_takeover').sum()),devage=('device_age_days','median'))
print(t.round(3))
f=tr[(tr.dn>=420000)&(tr.dn<428500)]; f['b']=pd.cut(f.dn,np.linspace(420000,428500,18)).astype(str)
print(f.groupby('b').agg(n=('label','size'),ndev=('device_id','nunique'),fr=('label',lambda s:(s!='legit').mean()),top=('label',lambda s:s.value_counts().index[0]),devage=('device_age_days','median')).round(3))
g=tr[(tr.dn>=428500)]; print('legit 2nd phones', g.dn.min(), g.dn.max(), 'rows/dev', len(g)/g.device_id.nunique(), 'devage med', g.device_age_days.median())
print('fraud blk rows/dev', len(f)/f.device_id.nunique(), 'accts/dev', f.groupby('device_id').sender_id.nunique().mean())
